#!/usr/bin/env python3
"""Settings tables of the post port from the Android sources (one source of truth):
SettingsNumericRules.bounds (key -> min, max, integer), PreferenceKeys.HYBRID_DEFAULTS and MotionMode.DEFAULTS (key -> default).
  gen_settings_tables.py           write ios/Engine/post/SettingsTables.inc
  gen_settings_tables.py --check   exit 1 when the file is not what the Android sources give
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SETTINGS = ROOT / 'app/src/main/java/com/particlesdevs/photoncamera/settings'
OUT = ROOT / 'ios/Engine/post/SettingsTables.inc'


def switch_rows(body):
    out, pending = [], []
    for line in body.splitlines():
        pending += re.findall(r'case "([^"]+)"', line)
        m = re.search(r'return new double\[\]\{([^}]*)\}', line)
        if m:
            vals = [v.strip() for v in m.group(1).split(',')]
            out += [(k, vals) for k in pending]
            pending = []
        elif 'return null' in line:
            pending = []
    return out


def function(text, signature):
    body = text[text.index(signature):]
    return body[:body.index('\n    }\n')]


def bounds():
    """bounds(): the first switch (before the colour / hybrid rules) and the second one (after them)."""
    body = function((SETTINGS / 'SettingsNumericRules.java').read_text(), 'public static double[] bounds(String key)')
    parts = body.split('switch (key)')
    if len(parts) != 3:
        raise SystemExit('SettingsNumericRules.bounds: expected two switches')
    return switch_rows(parts[1]), switch_rows(parts[2])


def list_bounds():
    body = function((SETTINGS / 'SettingsNumericRules.java').read_text(), 'public static double[] listBounds(String key)')
    return switch_rows(body)


def defaults():
    text = (ROOT / 'app/src/main/java/com/particlesdevs/photoncamera/settings/PreferenceKeys.java').read_text()
    return re.findall(r'HYBRID_DEFAULTS\.put\("([^"]+)",\s*([-0-9.eE]+)f?\)', text)


def motion_defaults():
    text = (SETTINGS / 'MotionMode.java').read_text()
    body = text[text.index('static final Map<String, Float> DEFAULTS;'):]
    body = body[:body.index('DEFAULTS = ')]
    return re.findall(r'd\.put\("([^"]+)",\s*([-0-9.eE]+)f?\)', body)


def render():
    lines = ['// Generated by ios/tools/gen_settings_tables.py from the Android sources - do not edit.',
             '// SettingsNumericRules.bounds: {key, min, max, integer}; kBoundsLate: its switch after the colour / hybrid rules']
    early, late = bounds()
    for name, rows in (('kBounds', early), ('kBoundsLate', late)):
        lines.append('static const BoundRow %s[] = {' % name)
        for k, v in rows:
            lines.append('    {"%s", %s, %s, %s},' % (k, v[0], v[1], v[2]))
        lines.append('};')
    lines.append('// SettingsNumericRules.listBounds: {key, count, min, max, integer}')
    lines.append('static const ListBoundRow kListBounds[] = {')
    for k, v in list_bounds():
        lines.append('    {"%s", %s, %s, %s, %s},' % (k, v[0], v[1], v[2], v[3]))
    lines.append('};')
    lines.append('// PreferenceKeys.HYBRID_DEFAULTS: {key, default}')
    lines.append('static const DefaultRow kHybridDefaults[] = {')
    for k, v in defaults():
        lines.append('    {"%s", %sf},' % (k, v if '.' in v or 'e' in v.lower() else v + '.0'))
    lines.append('};')
    lines.append('// MotionMode.DEFAULTS: the «Движение» values of the hybrid keys it replaces')
    lines.append('static const DefaultRow kMotionDefaults[] = {')
    for k, v in motion_defaults():
        lines.append('    {"%s", %sf},' % (k, v if '.' in v or 'e' in v.lower() else v + '.0'))
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('ios/Engine/post/SettingsTables.inc is out of date: run ios/tools/gen_settings_tables.py')
            sys.exit(1)
        print('settings tables up to date')
    else:
        OUT.write_text(text)
        print(OUT, len(text.splitlines()), 'lines')
