#!/usr/bin/env python3
"""CcmPresets.ALL (the «Профиль матрицы» registry) into ios/Engine/post/color/CcmPresets.inc; --check: fail when out of date."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'app/src/main/java/com/scamera/app/processing/color/CcmPresets.java'
OUT = ROOT / 'ios/Engine/post/color/CcmPresets.inc'


def render():
    rows = re.findall(r'new Preset\((\d+), "((?:[^"\\]|\\.)*)", new float\[\]\{([^}]*)\}\)', SRC.read_text())
    if not rows:
        raise SystemExit('no presets found in ' + str(SRC))
    lines = ['// Generated by ios/tools/gen_ccm_presets.py from CcmPresets.java: do not edit.',
             '// CcmPresets.ALL: {id, name, white-balanced camera RGB -> linear sRGB}',
             'static const CcmPreset kCcmPresets[] = {']
    for pid, name, m in rows:
        vals = ', '.join(v.strip() for v in m.split(','))
        lines.append('    {%s, "%s", {%s}},' % (pid, name, vals))
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('ios/Engine/post/color/CcmPresets.inc is out of date: run ios/tools/gen_ccm_presets.py')
            sys.exit(1)
        print('CCM presets up to date')
    else:
        OUT.write_text(text)
        print(OUT, len(text.splitlines()), 'lines')
