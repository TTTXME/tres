// P624: SPIR-V of the «Статика» shaders for the worker's Vulkan backend (scam-static-spirv.h), from the one source in
// scam-static-shaders.h. Usage: gen_static_spirv <glslc> <out.h> [--check]
//   (build it after every shader change: it embeds scam-static-shaders.h; the committed header is made with the NDK's glslc)
//   g++ -std=c++17 -O1 -Iapp/src/main/cpp tools/static/gen_static_spirv.cpp -o /tmp/gen_static_spirv
//   /tmp/gen_static_spirv glslc app/src/main/cpp/scam-static-spirv.h            (regenerate)
//   /tmp/gen_static_spirv glslc app/src/main/cpp/scam-static-spirv.h --check    (host lane: every program compiles as GLSL ES
//   3.10 and Vulkan GLSL, and the committed header's source hashes match the current sources; glslc versions differ, so the
//   words themselves are not compared)
// Also compiles every program as GLSL ES 3.10 (the GLES fallback's text) so a source the drivers would refuse fails here.
#include "scam-static-shaders.h"
#include "scam-static-spirv.h"
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <sstream>
#include <vector>
#include <unistd.h>

using namespace scam::staticmerge;

static std::vector<uint32_t> compile(const std::string& glslc,const std::string& src,bool gles,const char* name){
    const char* tmp=std::getenv("TMPDIR");std::string tpl=std::string(tmp&&*tmp?tmp:"/tmp")+"/stspvXXXXXX";std::vector<char> dirv(tpl.begin(),tpl.end());dirv.push_back(0);char* dir=dirv.data();
    if(!mkdtemp(dir)){std::perror("mkdtemp");std::exit(2);}
    const std::string in=std::string(dir)+"/s.comp",out=std::string(dir)+"/s.spv";
    {std::ofstream f(in);f<<src;}
    const std::string cmd=glslc+(gles?" --target-env=opengl -fshader-stage=comp ":" --target-env=vulkan1.1 -O -fshader-stage=comp ")+in+" -o "+out+" 2>&1";
    std::FILE* p=popen(cmd.c_str(),"r");
    std::string msg;char buf[512];
    while(p&&std::fgets(buf,sizeof(buf),p))msg+=buf;
    const int rc=p?pclose(p):-1;
    if(rc!=0){std::fprintf(stderr,"%s (%s): glslc failed\n%s\n",name,gles?"GLSL ES 3.10":"Vulkan",msg.c_str());std::exit(1);}
    std::ifstream f(out,std::ios::binary);
    std::vector<char> b((std::istreambuf_iterator<char>(f)),std::istreambuf_iterator<char>());
    std::vector<uint32_t> w(b.size()/4);std::memcpy(w.data(),b.data(),w.size()*4);
    std::remove(in.c_str());std::remove(out.c_str());rmdir(dir);
    return w;
}

int main(int argc,char** argv){
    if(argc<3){std::fprintf(stderr,"usage: %s <glslc> <out.h> [--check]\n",argv[0]);return 2;}
    const std::string glslc=argv[1],outPath=argv[2];
    const bool check=argc>3&&std::string(argv[3])=="--check";
    std::ostringstream h;
    h<<"#pragma once\n// GENERATED by tools/static/gen_static_spirv.cpp from scam-static-shaders.h (P624): do not edit.\n"
       "// The SPIR-V (Vulkan 1.1, glslc -O) of every «Статика» program and the FNV-1a of its GLSL 450 source.\n#include <cstdint>\n"
       "namespace scam {\nnamespace staticmerge {\nstruct StSpv { const uint32_t* code; uint32_t words; uint64_t hash; };\n";
    std::vector<size_t> sizes;
    for(int i=0;i<spCount;++i){
        if(!std::strstr(stPrograms()[i].defines,"ST_SUBGROUP"))compile(glslc,stSource(i,true),true,stPrograms()[i].name); // the GLES text must compile too (the subgroup variant is Vulkan only)
        const std::string vk=stSource(i,false);
        const std::vector<uint32_t> w=compile(glslc,vk,false,stPrograms()[i].name);
        sizes.push_back(w.size());
        h<<"static const uint32_t kStSpv_"<<stPrograms()[i].name<<"["<<w.size()<<"]={";
        for(size_t j=0;j<w.size();++j){if(j%12==0)h<<"\n    ";char t[16];std::snprintf(t,sizeof(t),"0x%08x,",w[j]);h<<t;}
        h<<"};\n";
    }
    h<<"inline const StSpv* stSpv(){\n    static const StSpv t[]={\n";
    for(int i=0;i<spCount;++i){
        char t[64];std::snprintf(t,sizeof(t),"0x%016llxull",(unsigned long long)stHash(stSource(i,false)));
        h<<"        {kStSpv_"<<stPrograms()[i].name<<","<<sizes[size_t(i)]<<"u,"<<t<<"},\n";
    }
    h<<"    };\n    return t;\n}\n} // namespace staticmerge\n} // namespace scam\n";
    if(check){
        int stale=0;
        for(int i=0;i<spCount;++i)if(stSpv()[i].hash!=stHash(stSource(i,false))){std::fprintf(stderr,"%s: SPIR-V stale\n",stPrograms()[i].name);++stale;}
        if(stale){std::fprintf(stderr,"%s is stale: run tools/static/gen_static_spirv.cpp\n",outPath.c_str());return 1;}
        std::printf("static SPIR-V header current (%d programs, sources compile for GLES and Vulkan)\n",int(spCount));return 0;
    }
    std::ofstream(outPath)<<h.str();
    std::printf("wrote %s (%d programs)\n",outPath.c_str(),int(spCount));
    return 0;
}
