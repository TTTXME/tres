#!/usr/bin/env python3
"""P683: the post pipeline's default program recipes (app/src/main/assets/shaders/default_recipes.txt).

The idle warm-up (GLProg.warmUp) compiles the programs whose recipes earlier shots kept (P371); a clean install has none, so its
first shot compiled every program («50 compiled in 2004 ms ... disk 0 hit / 50 miss», vivo V2405A). The APK now carries the
recipes this tool reads off the code: every use of an asset program by name (useAssetProgram / useUtilProgram with a literal name)
whose defines are all set by literal, unconditional setDefine calls on the same program object between the previous program and
it (none: the source as it is). Their order is the code's; GLInterface.readProgram makes the same source from them as the shot
does, so the warm-up's driver binaries are the ones the shot loads. A use with a define under a condition or of a computed value
is left out (the shot compiles it, as before, and keeps its recipe for the next warm-up). The programs stay the same.

Line format: <kind A|U> <name> <compute 0|1> then the defines NAME=VALUE in order, or '-' for none ('#' lines are comments).

usage: make_default_recipes.py           write the asset
       make_default_recipes.py --check   the asset is what the code gives now (CI: never stale), every asset exists, every
                                         define names a #define of its source, every program compiles (glslc, when found)
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JAVA = ROOT / 'app/src/main/java/com/scamera/app'
SH = ROOT / 'app/src/main/assets/shaders'
OUT = SH / 'default_recipes.txt'

USE = re.compile(r'\b(\w+)\.(useAssetProgram|useUtilProgram)\(\s*("[^"]+"|[A-Z][A-Z0-9_]*)\s*(?:,\s*(true|false))?\s*\)\s*;')
# a define: unconditional, or under a one-line condition whose default is known (CONDITIONS)
DEFINE = re.compile(r'^\s*(?:if\s*\((.+)\)\s*)?(\w+)\.setDefine\(\s*"([A-Z0-9_]+)"\s*,\s*(.+?)\s*\)\s*;\s*(//.*)?$')
LITERAL = re.compile(r'^(-?\d+|"[^"\s=]*"|true|false|[a-z]\w*)$')
FOR = re.compile(r'^\s*for\s*\(\s*int\s+(\w+)\s*=\s*(\d+)\s*;\s*\1\s*<\s*(\d+)\s*;\s*\1\+\+\s*\)')
CONST = re.compile(r'static\s+final\s+String\s+([A-Z][A-Z0-9_]*)\s*=\s*"([^"]+)"\s*;')
# where looking back for a program's defines stops: another program, a draw, a method's start
BOUND = re.compile(r'use\w*Program\(|drawBlocks\(|^\s*(public|private|protected|static)\b[^=;]*\)\s*(throws [^{]*)?\{\s*$')
# The conditions of one-line defines whose value under the default settings is known: True - the define is set by default,
# False - not. A condition not listed leaves its program out. --check fails when one is no longer in the code (stale).
CONDITIONS = {
    'band != null': False,                 # P677: V1's edge-aware bands on V2's pyramid, off by default (WhyTone.v2Bands)
    'jbu > 0f': False,                     # P673: the owner's joint bilateral upsampling, off by default
    'scale == 2': False,                   # WhyV2Fusion: the pyramid at the merge's own size unless the photo is halved
    'pipeline.p3Output': False,            # «Цветовое пространство»: sRGB by default
    'lut != null': False,                  # no LUT / film by default
    '!pipeline.tenBitOutput': True,        # JPEG by default: the 8-bit output
    'v2.fusedScale > 1': False,            # WhyV2Fusion: the fusion at the full grid by default
    'hlPlan != null': True,                # P713: WhyCombine's highlight mask on its coarse grid (CoarseMask) from a ~1 MP whyLow up
    'hw != null': True,                    # WhyCombine: the highlight mask's blur with its weights from the CPU (hlmask_fast, on)
}
# helper methods that take a program and its MODE: pattern -> (kind, asset or None: the call's first argument, MODE group)
HELPERS = [
    (re.compile(r'^\s*fusionProgram\(\s*"([^"]+)"\s*,\s*(\d+|[a-z]\w*)\s*,'), None),        # WhyFusion: MODE, GAMMA_TYPE (pure power: none)
    (re.compile(r'^\s*weightsProgram\(\s*(\d+|[a-z]\w*)\s*,'), 'why/gf'),                      # WhyFusion.weightsProgram: why/gf in MODE
]
# CaNetP.use(g, single("K", "V")): its SHADER with one define
CANET = re.compile(r'^\s*use\(\s*g\s*,\s*single\(\s*"([A-Z0-9_]+)"\s*,\s*"([^"\s=]+)"\s*\)\s*\)\s*;')


def loop_values(lines, i, var):
    """The values of {@code var} of the for loop around line i (its header within 12 lines above), or None."""
    for j in range(i - 1, max(-1, i - 12), -1):
        m = FOR.match(lines[j])
        if m and m.group(1) == var:
            return [str(v) for v in range(int(m.group(2)), int(m.group(3)))]
    return None


HEADER = ('# P683: the post programs the idle warm-up compiles on a clean install (GLProg.warmUp, no kept recipes yet).\n'
          '# Generated by tools/make_default_recipes.py from the code - do not edit; CI checks it is current.\n'
          '# <kind A: shaders/NAME.glsl, U: shaders/utils/NAME.glsl> <name> <compute 0|1> <NAME=VALUE ... | ->\n')


def recipes(used=None):
    """The recipes the code gives; {@code used}: the CONDITIONS met (for --check)."""
    found = {}
    for f in sorted(JAVA.rglob('*.java')):
        text_ = f.read_text(encoding='utf-8')
        lines = text_.split('\n')
        consts = dict(CONST.findall(text_))
        for i, line in enumerate(lines):
            m = USE.search(line)
            if m and not line[:m.start()].strip():
                receiver, method, name, compute = m.groups()
                name = name.strip('"') if name.startswith('"') else consts.get(name)
                if name is None:
                    continue
                kind = 'A' if method == 'useAssetProgram' else 'U'
                for defines in program_defines(lines, i, receiver, used):
                    found.setdefault((kind, name, '1' if compute == 'true' else '0', tuple(defines)), None)
                continue
            for pattern, asset in HELPERS:
                h = pattern.match(line)
                if not h:
                    continue
                name, mode = (asset, h.group(1)) if asset else (h.group(1), h.group(2))
                modes = [mode] if mode.isdigit() else loop_values(lines, i, mode)
                for v in modes or []:
                    found.setdefault(('A', name, '0', (('MODE', v),)), None)
            c = CANET.match(line)
            if c and 'SHADER' in consts:
                found.setdefault(('A', consts['SHADER'], '0', ((c.group(1), c.group(2)),)), None)
    return sorted(found)


def program_defines(lines, i, receiver, used):
    """The define lists of the program used on line i: one, or one per value of a loop variable; none when unknown."""
    indent = len(lines[i]) - len(lines[i].lstrip())
    defines = []
    for j in range(i - 1, max(-1, i - 40), -1):
        prev = lines[j]
        if BOUND.search(prev):
            break
        if 'setDefine' not in prev and 'setLayout' not in prev:
            continue
        d = DEFINE.match(prev)
        if not d or d.group(2) != receiver or len(prev) - len(prev.lstrip()) != indent:
            return []  # computed, nested or another object's: the shot's own compile
        cond = d.group(1)
        if cond is not None:
            cond = cond.strip()
            if cond not in CONDITIONS:
                return []
            if used is not None:
                used.add(cond)
            if not CONDITIONS[cond]:
                continue
        value = d.group(4)
        if not LITERAL.match(value):
            return []  # a computed value
        value = {'true': '1', 'false': '0'}.get(value, value.strip('"'))
        defines.insert(0, (d.group(3), value))
    out = [[]]
    for n, v in defines:
        if v[0].isalpha() and not v.isupper():
            values = loop_values(lines, i, v)
            if values is None:
                return []
            out = [o + [(n, x)] for o in out for x in values]
        else:
            out = [o + [(n, v)] for o in out]
    return out


def text(rs):
    rows = []
    for kind, name, compute, defines in rs:
        rows.append(' '.join([kind, name, compute] + (['%s=%s' % d for d in defines] if defines else ['-'])))
    return HEADER + '\n'.join(rows) + '\n'


def source_of(kind, name):
    return (SH / (name + '.glsl')) if kind == 'A' else (SH / 'utils' / (name + '.glsl'))


def expand(src, depth=0):
    """GLInterface.readProgram's #import (shaders/utils/import_NAME.glsl, else shaders/utils/NAME.glsl)."""
    out = []
    for line in src.replace('\r\n', '\n').split('\n'):
        if '#import' in line and '//' not in line.split('#import')[0]:
            n = line.split('#import', 1)[1].strip().split()[0]
            f = SH / 'utils' / ('import_' + n + '.glsl')
            if not f.exists():
                f = SH / 'utils' / (n + '.glsl')
            if not f.exists() or depth > 4:
                return None
            sub = expand(f.read_text(encoding='utf-8'), depth + 1)
            if sub is None:
                return None
            out.append(sub)
        else:
            out.append(line)
    return '\n'.join(out)


def processed(src, defines):
    """readProgram's defines: a #define line naming ' NAME ' takes the first matching define's value."""
    out = []
    for line in src.split('\n'):
        if defines and '#define' in line:
            for n, v in defines:
                if ' %s ' % n in line:
                    line = '#define %s %s' % (n, v)
                    break
        out.append(line)
    return '\n'.join(out)


def with_header(src):
    if '#version' in src:
        return src
    lines = src.split('\n')
    k = 0
    while k < len(lines) and (lines[k].strip().startswith('#extension') or not lines[k].strip()):
        k += 1
    return '\n'.join(['#version 310 es'] + lines[:k] + ['precision highp int;'] + lines[k:])


def find_glslc():
    found = shutil.which('glslc')
    if found:
        return found
    for env in ('ANDROID_NDK_HOME', 'ANDROID_HOME', 'ANDROID_SDK_ROOT'):
        base = os.environ.get(env)
        if not base:
            continue
        for pattern in ('ndk/*/shader-tools/*/glslc', 'shader-tools/*/glslc'):
            hits = sorted(Path(base).glob(pattern))
            if hits:
                return str(hits[-1])
    return None


def check():
    failures = []
    used = set()
    rs = recipes(used)
    for cond in sorted(set(CONDITIONS) - used):
        failures.append('the condition %r of CONDITIONS is no longer in the code (stale: remove or update it)' % cond)
    want = text(rs)
    got = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
    if got != want:
        failures.append('%s is not what the code gives now: run python3 tools/make_default_recipes.py' % OUT.relative_to(ROOT))
    glslc = find_glslc()
    compiled = 0
    with tempfile.TemporaryDirectory() as tmp:
        for kind, name, compute, defines in rs:
            f = source_of(kind, name)
            if not f.exists():
                failures.append('%s %s: no %s' % (kind, name, f.relative_to(ROOT)))
                continue
            src = expand(f.read_text(encoding='utf-8'))
            if src is None:
                failures.append('%s: an #import is missing' % name)
                continue
            for n, _ in defines:
                if not re.search(r'#define\s+%s(\s|$)' % n, src):
                    failures.append('%s: the define %s is no #define of its source (renamed or gone)' % (name, n))
            if glslc is None:
                continue
            path = Path(tmp) / ('p%d.%s' % (compiled, 'comp' if compute == '1' else 'frag'))
            path.write_text(with_header(processed(src, defines)), encoding='utf-8')
            r = subprocess.run([glslc, '--target-env=opengl', '-std=310es', '-fauto-map-locations', '-fauto-bind-uniforms', '-o', os.devnull, str(path)], capture_output=True, text=True)
            if r.returncode != 0:
                failures.append('%s %s: glslc: %s' % (name, defines, (r.stderr or r.stdout).strip().split('\n')[0]))
            compiled += 1
    for f in failures:
        print('FAIL ' + f)
    print('     %d default recipes from the code%s' % (len(rs), ', %d compiled by glslc' % compiled if glslc else ' (no glslc: not compiled)'))
    print('ALL OK' if not failures else 'FAILED: %d' % len(failures))
    return 1 if failures else 0


def main(argv):
    if '--check' in argv:
        return check()
    OUT.write_text(text(recipes()), encoding='utf-8')
    print('%s: %d recipes' % (OUT.relative_to(ROOT), len(recipes())))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
