#!/usr/bin/env python3
"""The concept's line icons (research/concept/*.dc.html, their `const I = {...}` path tables: 24 x 24, 2 px round strokes) as
VectorDrawables: res/drawable/<prefix><name>.xml, white strokes (tinted by the views). Usage:
  concept_icons.py --board Viewfinder --prefix cv_ [--only bolt,timer] [--stroke 2] [--check]
  concept_icons.py --board Hybrid --table ICONS --tones HUES --prefix cs_ic_ --stroke 2.1 [--check]   (another table: `const ICONS = {"settings_ic_x": ["d", hue]}`
      as JSON, or `const D = {x: 'd'}`; a "settings_ic_" before a name is dropped)
  concept_icons.py --inline --prefix cs_ [--check]   (the icons drawn inline in the boards' markup: back, reset, search, chevrons,
      the menu's tick; each at its own viewBox, size and stroke, checked to be still in its board)"""
import argparse, json, os, re, sys


def _unused():
    """P655: the drawables the app does not use (tools/icons/unused.txt): not generated, not checked."""
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'unused.txt')
    with open(p, encoding='utf-8') as f:
        return {l.strip() for l in f if l.strip() and not l.startswith('#')}


UNUSED = _unused()

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def board_text(board):
    return open(os.path.join(ROOT, 'research', 'concept', board + '.dc.html'), encoding='utf-8').read()


def tones(board, name):
    """{hue: light tone} of a board's `const HUES = { blue: ['#004786', '#A4C9FF'], ... }` (the tile's dark tone, the icon's light one)."""
    m = re.search(r'const ' + name + r' = \{(.*?)\};', board_text(board), re.S)
    if not m:
        raise SystemExit('no tone table %s in %s' % (name, board))
    return {k: b for k, a, b in re.findall(r"(\w+):\s*\['(#[0-9A-Fa-f]{6})',\s*'(#[0-9A-Fa-f]{6})'\]", m.group(1))}


def hues(board, name):
    """{icon: hue} of a JSON table whose entries are [d, hue]."""
    m = re.search(r'const ' + name + r' = (\{.*?\});\n', board_text(board), re.S)
    try:
        return {re.sub(r'^settings_ic_', '', k): v[1] for k, v in json.loads(m.group(1)).items() if isinstance(v, list) and k != '_'}
    except (ValueError, AttributeError):
        return {}


def table(board, name='I'):
    s = board_text(board)
    if name == 'I':
        m = re.search(r'const I = \{(.*?)\n\s*\};', s, re.S)
        if not m:
            raise SystemExit('no icon table in ' + board)
        return dict(re.findall(r"(\w+):\s*'([^']*)'", m.group(1)))
    m = re.search(r'const ' + name + r' = (\{.*?\});\n', s, re.S)
    if not m:
        raise SystemExit('no table %s in %s' % (name, board))
    try:
        raw = {k: (v[0] if isinstance(v, list) else v) for k, v in json.loads(m.group(1)).items()}
    except ValueError:
        raw = dict(re.findall(r"(\w+):\s*'([^']*)'", m.group(1)))
    return {re.sub(r'^settings_ic_', '', k): v for k, v in raw.items() if k != '_'}


# the icons drawn inline in the boards' markup: name -> (board, viewBox w, h, size w, h, stroke, d)
INLINE = {
    'back': ('Hybrid', 24, 24, 20, 20, '2.4', 'M15 5l-7 7 7 7'),
    'page_reset': ('Hybrid', 24, 24, 19, 19, '2.3', 'M4 12a8 8 0 1 0 2.3-5.6 M4 4v4.5h4.5'),
    'search': ('Hybrid', 24, 24, 19, 19, '2.2', 'M10.5 4a6.5 6.5 0 1 0 0 13a6.5 6.5 0 1 0 0-13z M15.5 15.5L20 20'),
    'chevron': ('Hybrid', 9, 15, 9, 15, '2.2', 'M1.5 1.5l6 6-6 6'),
    'updown': ('Hybrid', 13, 17, 13, 17, '2', 'M2.5 6l4-4 4 4 M2.5 11l4 4 4-4'),
    'tick': ('Hybrid', 15, 13, 15, 13, '2.4', 'M1.5 7l4 4.2 8-9.7'),
    'caret': ('Modules', 24, 24, 12, 12, '3', 'M6 9l6 6 6-6'),
    'chevron_open': ('Modules', 24, 24, 14, 14, '2.6', 'M9 5l7 7-7 7'),
    'compare': ('FilmPage', 24, 24, 18, 18, '2.4', 'M9 6l-5 6 5 6 M15 6l5 6-5 6'),
    'trash': ('Modules', 24, 24, 17, 17, '2.1', 'M5 7h14 M9 7V5h6v2 M7 7l1 13h8l1-13'),
}


def vector(d, stroke, box=(24, 24, 24, 24), colour='#FFFFFFFF'):
    vw, vh, w, h = box
    paths = [p.strip() for p in re.split(r'\s(?=M)', d) if p.strip()]
    body = ''.join(
        '    <path android:pathData="%s" android:fillColor="#00000000" android:strokeColor="%s"\n'
        '        android:strokeWidth="%s" android:strokeLineCap="round" android:strokeLineJoin="round" />\n' % (p, colour, stroke)
        for p in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icons/concept_icons.py from the concept; do not edit -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="%sdp" android:height="%sdp"\n'
            '    android:viewportWidth="%s" android:viewportHeight="%s">\n' % (w, h, vw, vh) + body + '</vector>\n')


def main():
    a = argparse.ArgumentParser()
    a.add_argument('--board', default='')
    a.add_argument('--table', default='I')
    a.add_argument('--inline', action='store_true')
    a.add_argument('--tones', default='', help="the board's tone table: each icon's stroke in its hue's light tone (the row "
                   "tints it; SettingsTiles reads the tone back to pick the tile's pair)")
    a.add_argument('--prefix', required=True)
    a.add_argument('--only', default='')
    a.add_argument('--stroke', default='2')
    a.add_argument('--check', action='store_true')
    o = a.parse_args()
    if not o.inline and not o.board:
        a.error('--board or --inline')
    if o.inline:
        icons = {}
        for name, (board, vw, vh, w, h, stroke, d) in INLINE.items():
            if d not in board_text(board):
                raise SystemExit('inline icon %s is no longer in %s' % (name, board))
            icons[name] = (d, stroke, (vw, vh, w, h))
    else:
        icons = {k: (d, o.stroke, (24, 24, 24, 24)) for k, d in table(o.board, o.table).items()}
    colours = {}
    if o.tones:
        light, hue = tones(o.board, o.tones), hues(o.board, o.table)
        colours = {k: '#FF' + light[h].lstrip('#').upper() for k, h in hue.items() if h in light}
    only = [x for x in o.only.split(',') if x]
    out = os.path.join(ROOT, 'app', 'src', 'main', 'res', 'drawable')
    bad = []
    for name, (d, stroke, box) in icons.items():
        if only and name not in only:
            continue
        f = os.path.join(out, o.prefix + re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower() + '.xml')
        if os.path.basename(f)[:-4] in UNUSED:
            continue
        text = vector(d, stroke, box, colours.get(name, '#FFFFFFFF'))
        if o.check:
            if not os.path.isfile(f) or open(f, encoding='utf-8').read() != text:
                bad.append(os.path.basename(f))
        else:
            with open(f, 'w', encoding='utf-8', newline='\n') as fh:
                fh.write(text)
    if bad:
        print('concept icons differ: ' + ', '.join(bad))
        return 1
    print('%s %d icons from %s' % ('checked' if o.check else 'wrote', len(only) or len(icons), o.board or 'the inline markup'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
