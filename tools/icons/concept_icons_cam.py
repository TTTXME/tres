#!/usr/bin/env python3
"""P583 (the camera boards: Viewfinder / ViewfinderLand, their variants and the Pro chips). The concept's line icons (research/concept/*.dc.html, their `const I = {...}` path tables: 24 x 24, 2 px round strokes) as
VectorDrawables: res/drawable/<prefix><name>.xml, white strokes (tinted by the views). Usage:
  concept_icons.py --board Viewfinder --prefix cv_ [--only bolt,timer] [--stroke 2] [--check]"""
import argparse, os, re, sys


def _unused():
    """P655: the drawables the app does not use (tools/icons/unused.txt): not generated, not checked."""
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'unused.txt')
    with open(p, encoding='utf-8') as f:
        return {l.strip() for l in f if l.strip() and not l.startswith('#')}


UNUSED = _unused()

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def table(board):
    s = open(os.path.join(ROOT, 'research', 'concept', board + '.dc.html'), encoding='utf-8').read()
    m = re.search(r'const I = \{(.*?)\n\s*\};', s, re.S)
    if not m:
        raise SystemExit('no icon table in ' + board)
    return dict(re.findall(r"(\w+):\s*'([^']*)'", m.group(1)))


# The board's own variants of its icons: (icon, file suffix, stroke, filled) - the torch filled while on, the mode switch's glyphs
# at its 1.9 stroke (the photo filled while chosen, fill-rule evenodd: the lens a hole).
VARIANTS = {'Viewfinder': [('bolt', '_fill', '2', True), ('run', '_m', '1.9', False), ('photo', '_m', '1.9', False),
                           ('photo', '_m_fill', '1.9', True)]}
# P583: the Pro panel's chips live in the circularbar library (it cannot see the app's drawables): pro_ic_<chip> there, from
# the board's icons (ISO, Выдержка, Яркость, Фокус, Цвет, «Всё на авто»).
LIB_PRO = {'Viewfinder': {'iso': 'iso', 'shutter': 'shutter', 'ev': 'sun', 'focus': 'focus', 'wb': 'thermo', 'auto': 'auto'}}
# The board's inline glyphs (outside its icon table): name -> (path, stroke, viewport w, viewport h).
INLINE = {'Viewfinder': {'minus': ('M5 12h14', '3.6', 24, 24), 'chev_right': ('M9 5l7 7-7 7', '2.6', 24, 24),
                         'chev_down': ('M6 9l6 6 6-6', '2.6', 24, 24), 'chev_left': ('M15 5l-7 7 7 7', '2.6', 24, 24),
                         'check': ('M1.5 7l4 4.2 8-9.7', '2.4', 15, 13), 'cross': ('M6 6l12 12 M18 6L6 18', '3.4', 24, 24),
                         'plus_bold': ('M5 12h14 M12 5v14', '2.6', 24, 24),
                         # P590: the flash modes (the bolt of the table): off with a slash, auto with a small «A», the torch a
                         # flashlight (head, rim, body, switch) in the same 2 px round strokes
                         'bolt_off': ('M13.2 2.8L5.5 13.4h5.7l-1 7.8 7.8-10.6h-5.8z M3.5 3.5l17 17', '2', 24, 24),
                         'bolt_auto': ('M11.2 2.8L3.5 13.4h5.7l-1 7.8 7.8-10.6h-5.8z M16.5 21l2.5-6.5 2.5 6.5 M17.4 18.8h3.2', '2', 24, 24),
                         'torch': ('M7 3h10v3l-2 4H9L7 6z M7 6h10 M9 10v10a1 1 0 0 0 1 1h4a1 1 0 0 0 1-1V10 M12 13.5v2', '2', 24, 24)}}


def filled(d, stroke):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icons/concept_icons.py from the concept; do not edit -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24">\n'
            '    <path android:pathData="%s" android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:strokeColor="#FFFFFFFF"\n'
            '        android:strokeWidth="%s" android:strokeLineCap="round" android:strokeLineJoin="round" />\n</vector>\n' % (d, stroke))


def vector(d, stroke, vw=24, vh=24):
    paths = [p.strip() for p in re.split(r'\s(?=M)', d) if p.strip()]
    body = ''.join(
        '    <path android:pathData="%s" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF"\n'
        '        android:strokeWidth="%s" android:strokeLineCap="round" android:strokeLineJoin="round" />\n' % (p, stroke)
        for p in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icons/concept_icons.py from the concept; do not edit -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="%ddp" android:height="%ddp"\n'
            '    android:viewportWidth="%d" android:viewportHeight="%d">\n' % (vw, vh, vw, vh) + body + '</vector>\n')


def main():
    a = argparse.ArgumentParser()
    a.add_argument('--board', required=True)
    a.add_argument('--prefix', required=True)
    a.add_argument('--only', default='')
    a.add_argument('--stroke', default='2')
    a.add_argument('--check', action='store_true')
    o = a.parse_args()
    icons = table(o.board)
    only = [x for x in o.only.split(',') if x]
    out = os.path.join(ROOT, 'app', 'src', 'main', 'res', 'drawable')
    bad = []
    files = []
    for name, d in icons.items():
        if only and name not in only:
            continue
        files.append((re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower(), vector(d, o.stroke)))
    if not only:
        for name, suffix, stroke, fill in VARIANTS.get(o.board, []):
            files.append((name + suffix, filled(icons[name], stroke) if fill else vector(icons[name], stroke)))
        for name, (d, stroke, vw, vh) in INLINE.get(o.board, {}).items():
            files.append((name, vector(d, stroke, vw, vh)))
    targets = [(os.path.join(out, o.prefix + name + '.xml'), text) for name, text in files]
    if not only:
        lib = os.path.join(ROOT, 'circularbarlib', 'src', 'main', 'res', 'drawable')
        for chip, name in LIB_PRO.get(o.board, {}).items():
            targets.append((os.path.join(lib, 'pro_ic_%s.xml' % chip), vector(icons[name], o.stroke)))
    targets = [(f, text) for f, text in targets if os.path.basename(f)[:-4] not in UNUSED]
    for f, text in targets:
        if o.check:
            if not os.path.isfile(f) or open(f, encoding='utf-8').read() != text:
                bad.append(os.path.basename(f))
        else:
            with open(f, 'w', encoding='utf-8', newline='\n') as fh:
                fh.write(text)
    if bad:
        print('concept icons differ: ' + ', '.join(bad))
        return 1
    print('%s %d icons from %s' % ('checked' if o.check else 'wrote', len(targets), o.board))
    return 0


if __name__ == '__main__':
    sys.exit(main())
